#!/usr/bin/env node
/**
 * Pack Code/TradeScanner/scanner.html + matcher.js + fruitSignatures.json into
 * Code/TradeScanner/scannerHtml.js, the string TradeScannerModal hands to
 * react-native-webview (source={{ html }}). Ships inside the app bundle.
 *
 *   npm run scanner:build     (after editing any of the three files)
 *
 * __tests__/tradeScanner.test.js fails when they drift apart.
 */
const fs = require('fs');
const path = require('path');

const dir = path.resolve(__dirname, '../../Code/TradeScanner');

function build() {
  const html = fs.readFileSync(path.join(dir, 'scanner.html'), 'utf8');
  const matcher = fs.readFileSync(path.join(dir, 'matcher.js'), 'utf8');
  const sigs = JSON.stringify(JSON.parse(fs.readFileSync(path.join(dir, 'fruitSignatures.json'), 'utf8')));
  // Function replacers: the inlined code contains "$" sequences.
  return html.replace('/*__MATCHER__*/', () => matcher).replace('/*__SIGNATURES__*/null', () => sigs);
}

module.exports = { build };

if (require.main === module) {
  const page = build();
  fs.writeFileSync(
    path.join(dir, 'scannerHtml.js'),
    `// GENERATED by scripts/trade-scanner/build-html.js from Code/TradeScanner/scanner.html. Do not edit.\nexport default ${JSON.stringify(page)};\n`,
  );
  console.log(`scannerHtml.js written (${(page.length / 1024).toFixed(1)} KB)`);
}
