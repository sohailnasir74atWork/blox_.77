#!/usr/bin/env node
/**
 * Pack Code/Raid/game/raid.html into Code/Raid/raidGameHtml.js, the string
 * the app hands to react-native-webview (source={{ html }}). The game ships
 * inside the app bundle: no download, no remote code.
 *
 *   npm run raid:build        (after every edit to raid.html)
 *
 * __tests__/raidGame.test.js fails when the two drift apart.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '../..');
const src = path.join(root, 'Code/Raid/game/raid.html');
const out = path.join(root, 'Code/Raid/raidGameHtml.js');
const html = fs.readFileSync(src, 'utf8');
fs.writeFileSync(out, `// GENERATED by scripts/raid/build-game.js from Code/Raid/game/raid.html. Do not edit.\nexport default ${JSON.stringify(html)};\n`);
console.log(`raidGameHtml.js written (${(html.length / 1024).toFixed(1)} KB)`);
